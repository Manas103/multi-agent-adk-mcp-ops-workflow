"""Deterministic seed data for the legacy directory and the policy document
store: 60 employees, 2-3 assets each, and 6 real-shaped offboarding policy
documents. Regenerated by scripts/run_benchmark.py --reset-db; never hand
edited after a run so every benchmark run starts from the same state.
"""

from __future__ import annotations

import random

from . import db

ACCESS_LEVELS = ["STANDARD", "ADMIN", "ALL"]
ASSET_DESCRIPTIONS = ["laptop", "monitor", "badge", "mobile phone", "VPN token"]

POLICY_DOCS = [
    ("POL-001", "Standard Access Revocation", "Standard-level access must be revoked within 24 hours of the employee's last working day. No manager approval is required for STANDARD or ADMIN levels."),
    ("POL-002", "ALL-Level Access Revocation", "ALL-level access (database and production infrastructure) revocation requires a security team sign-off recorded on the ticket before the revoke action is approved."),
    ("POL-003", "Asset Return Window", "Laptops, mobile phones and VPN tokens must be returned within 10 business days. A compliance ticket of type ASSET_RETURN is opened automatically if an asset remains unreturned at day 10."),
    ("POL-004", "Badge Deactivation", "Physical badges are deactivated by security operations, not by this workflow; a badge asset is tracked here only for return-logistics purposes."),
    ("POL-005", "Monitor and Peripheral Return", "Monitors and other peripherals follow the same 10-business-day return window as POL-003 but do not trigger an automatic compliance ticket if unreturned."),
    ("POL-006", "Contractor Offboarding Exception", "Contractors (not covered by this corpus) follow a 48-hour access revocation window instead of 24 hours; included here as a document a retrieval tool must be able to distinguish from POL-001."),
]


def _rng(seed: int) -> random.Random:
    return random.Random(seed)


def seed(seed_value: int = 20261013) -> dict:
    """Writes deterministic rows and returns the raw scenario data the task
    corpus is built from, so the corpus and the database never drift apart."""

    rng = _rng(seed_value)
    employees = []
    assets = []
    asset_id_counter = 1

    with db.cursor() as cur:
        for employee_id in range(1, 61):
            name = f"employee-{employee_id:03d}"
            access_level = rng.choice(ACCESS_LEVELS)
            cur.execute(
                "INSERT INTO offboard.employees (employee_id, name, access_level) VALUES (%s, %s, %s)",
                (employee_id, name, access_level),
            )
            employees.append({"employee_id": employee_id, "name": name, "access_level": access_level})

            n_assets = rng.randint(2, 3)
            emp_assets = []
            for _ in range(n_assets):
                description = rng.choice(ASSET_DESCRIPTIONS)
                cur.execute(
                    "INSERT INTO offboard.assets (asset_id, employee_id, description) VALUES (%s, %s, %s)",
                    (asset_id_counter, employee_id, description),
                )
                emp_assets.append({"asset_id": asset_id_counter, "description": description})
                asset_id_counter += 1
            assets.append(emp_assets)

        for doc_id, title, body in POLICY_DOCS:
            cur.execute(
                "INSERT INTO offboard.policy_docs (doc_id, title, body) VALUES (%s, %s, %s)",
                (doc_id, title, body),
            )

        # 30 pre-existing OPEN asset-return tickets, one per employee 1..30,
        # so the status_update task type has something real to close without
        # depending on another task's proposal having already run.
        preseeded_tickets = []
        for employee_id in range(1, 31):
            asset_id = assets[employee_id - 1][0]["asset_id"]
            cur.execute(
                """INSERT INTO offboard.tickets (employee_id, ticket_type, asset_id, status)
                   VALUES (%s, 'ASSET_RETURN', %s, 'OPEN') RETURNING ticket_id""",
                (employee_id, asset_id),
            )
            ticket_id = cur.fetchone()["ticket_id"]
            preseeded_tickets.append({"ticket_id": ticket_id, "employee_id": employee_id, "asset_id": asset_id})

    return {
        "employees": employees,
        "assets_by_employee": assets,
        "policy_docs": POLICY_DOCS,
        "preseeded_tickets": preseeded_tickets,
    }
